// Public calls: a thesis on a position you hold, tracked to its result, with agree / disagree votes.
const API = process.env.API || 'http://127.0.0.1:8787', MOCK = process.env.MOCK || 'http://127.0.0.1:8500';
let pass = 0, fail = 0;
const ok = (c, l, x = '') => { c ? pass++ : fail++; console.log(`${c ? 'PASS' : 'FAIL'}  ${l}${x ? '  ' + x : ''}`); };
const sleep = ms => new Promise(r => setTimeout(r, ms));
const tok = async q => (await (await fetch(`${MOCK}/token?${new URLSearchParams(q)}`)).json()).token;
async function call(path, token, body) {
  const h = { 'Content-Type': 'application/json' }; if (token) h.Authorization = 'Bearer ' + token;
  const r = await fetch(API + path, { method: body ? 'POST' : 'GET', headers: h, body: body && JSON.stringify(body) });
  return { status: r.status, j: await r.json() };
}
const setPx = async px => { await fetch(`${MOCK}/set`, { method: 'POST', body: JSON.stringify({ px }) }); await sleep(3000); };
const id = Math.random().toString(36).slice(2, 7);
const a = await tok({ uid: 'call-a-' + id, name: 'Caller ' + id }), b = await tok({ uid: 'call-b-' + id, name: 'Voter ' + id });
const owner = await tok({ uid: 'call-owner', name: 'Owner', email: 'owner@example.com', verified: '1' });
await setPx({ BTC: 78000 });
await call('/api/account', b);
let r = await call('/api/call', a, { coin: 'BTC', thesis: 'Breakout above the range with strong volume, targeting 82k.' });
ok(r.status === 400 && /hold|position/i.test(r.j.error), 'no call without a position', r.j.error);
r = await call('/api/order', a, { coin: 'BTC', side: 'buy', size: 2000, unit: 'usd', leverage: 10 });
ok(r.status === 200, 'open a BTC long at 10x');
r = await call('/api/call', a, { coin: 'BTC', thesis: 'up only' });
ok(r.status === 400 && /at least/.test(r.j.error), 'thesis too short is refused', r.j.error);
r = await call('/api/call', a, { coin: 'BTC', thesis: 'Join my group at t.me/pumpgroup for more signals like this one' });
ok(r.status === 400 && /Links/.test(r.j.error), 'links and handles are refused', r.j.error);
r = await call('/api/call', a, { coin: 'BTC', thesis: 'This shit is going to the moon, absolutely certain of it' });
ok(r.status === 400 && /clean/.test(r.j.error), 'swearing is refused', r.j.error);
const thesis = 'Reclaimed the weekly open and funding is flat, so longs are not crowded. Target 82k, invalid below 75k.';
r = await call('/api/call', a, { coin: 'BTC', thesis });
ok(r.status === 200 && r.j.id, 'call posted', (r.j.messages || [r.j.error])[0]);
const cid = r.j.id;
r = await call('/api/call', a, { coin: 'BTC', thesis });
ok(r.status === 400 && /already/.test(r.j.error), 'one open call per position', r.j.error);
r = await call(`/api/calls?id=${cid}`);
let c = r.j.calls && r.j.calls[0];
ok(c && c.side === 'long' && c.lev === 10 && c.thesis === thesis && c.outcome === 'open' && c.name && c.pid, 'feed shows it publicly, signed out too', c && `${c.name}: ${c.side} ${c.lev}x ${c.outcome}`);
await setPx({ BTC: 79560 });
c = (await call(`/api/calls?id=${cid}`)).j.calls[0];
ok(Math.abs(c.move - 0.02) < 0.002 && Math.abs(c.roe - 0.2) < 0.02, 'live result follows the price (+2% move, +20% at 10x)', `${(c.move * 100).toFixed(2)}% / ${(c.roe * 100).toFixed(1)}%`);
r = await call('/api/call/vote', a, { id: cid, vote: 1 });
ok(r.status === 400, "can't vote on your own call");
r = await call('/api/call/vote', b, { id: cid, vote: 1 });
ok(r.status === 200 && r.j.agree === 1 && r.j.my_vote === 1, 'someone else agrees');
r = await call('/api/call/vote', b, { id: cid, vote: -1 });
ok(r.j.agree === 0 && r.j.disagree === 1, 'and can change their mind');
c = (await call(`/api/calls?id=${cid}`, b)).j.calls[0];
ok(c.my_vote === -1 && c.disagree === 1, 'the feed remembers their vote');
r = await call('/api/close', a, { coin: 'BTC' });
c = (await call(`/api/calls?id=${cid}`)).j.calls[0];
ok(c.outcome === 'closed' && Math.abs(c.price - 79560) < 100 && c.closed_at, 'closing the position closes the call at the exit price', `${c.outcome} at ${c.price}`);
const pid = (await call('/api/account', a)).j.profile.pid;
r = await call(`/api/trader/${pid}`);
ok(r.j.calls && r.j.calls.some(x => x.id === cid), "the call is on the trader's profile");
r = await call(`/api/calls?sort=top`);
ok(r.j.calls.some(x => x.id === cid), 'it shows in the top calls of the week');
r = await call('/api/admin/call-remove', b, { id: cid });
ok(r.status === 403, 'only the owner can remove calls');
r = await call('/api/admin/call-remove', owner, { id: cid });
ok(r.status === 200, 'owner removes it');
ok(!(await call(`/api/calls?id=${cid}`)).j.calls.length, 'removed calls disappear');
await setPx({ BTC: 77800 });
console.log(`\n${pass} passed, ${fail} failed`);
process.exit(fail ? 1 : 0);
